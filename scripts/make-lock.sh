# make-lock.sh — resolve components.yaml into sdk.lock.yaml, then render
# build/<stage>/pins.hcl from the lock. Invoked as `make lock`.
#
#   make-lock.sh           resolve every ref and the base image, write the
#                          lock, render the pins
#   make-lock.sh --render  render the pins from the existing lock only
#
# Refs are resolved with `git ls-remote`, so no clone is needed. The
# component repos are public, so git needs no credentials. The base image digest is read from the Docker
# Hub registry API with curl.

set -euo pipefail

MANIFEST="${MANIFEST:-components.yaml}"
LOCK="${LOCK:-sdk.lock.yaml}"

command -v yq >/dev/null || { echo "make-lock: yq required" >&2; exit 1; }

log() { printf '[make-lock] %s\n' "$*" >&2; }

# License header of the generated files. The REUSE markers stop `reuse lint`
# from reading these lines as the header of this script.
# REUSE-IgnoreStart
spdx_header() {
    echo "# SPDX-FileCopyrightText: 2026 Openchip and Software Technologies, S.L."
    echo "# SPDX-License-Identifier: Apache-2.0"
}
# REUSE-IgnoreEnd

# Docker Hub image reference "name:tag" -> "docker.io/library/name:tag@sha256:...".
# The digest is that of the multi-platform index, as `docker pull` uses it.
resolve_image() {
    local ref="$1" name tag repo token digest
    name="${ref%%:*}"
    tag="${ref#*:}"
    [[ "$name" == */* ]] && repo="$name" || repo="library/${name}"
    token=$(curl -fsSL "https://auth.docker.io/token?service=registry.docker.io&scope=repository:${repo}:pull" \
            | yq -p json -r '.token')
    digest=$(curl -fsSI \
                -H "Authorization: Bearer ${token}" \
                -H 'Accept: application/vnd.oci.image.index.v1+json' \
                -H 'Accept: application/vnd.docker.distribution.manifest.list.v2+json' \
                "https://registry-1.docker.io/v2/${repo}/manifests/${tag}" \
             | tr -d '\r' | awk -F': ' 'tolower($1) == "docker-content-digest" {print $2}')
    [[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || { log "FATAL: cannot resolve ${ref}"; exit 1; }
    echo "docker.io/${repo}:${tag}@${digest}"
}

# Branch, then peeled tag, then tag, then a literal SHA.
resolve_ref() {
    local repo="$1" ref="$2" sha
    sha=$(git ls-remote "$repo" "refs/heads/${ref}" | awk '{print $1; exit}')
    [[ -n "$sha" ]] || sha=$(git ls-remote "$repo" "refs/tags/${ref}^{}" | awk '{print $1; exit}')
    [[ -n "$sha" ]] || sha=$(git ls-remote "$repo" "refs/tags/${ref}"     | awk '{print $1; exit}')
    if [[ -z "$sha" ]]; then
        [[ "$ref" =~ ^[0-9a-f]{40}$ ]] || { log "FATAL: cannot resolve ${ref} in ${repo}"; exit 1; }
        sha="$ref"
    fi
    echo "$sha"
}

write_lock() {
    local tmp c repo ref sha base_ref base_pinned
    tmp=$(mktemp)
    trap 'rm -f "$tmp"' RETURN

    base_ref=$(yq -r '.base_image' "$MANIFEST")
    log "resolving base image ${base_ref}"
    base_pinned=$(resolve_image "$base_ref")

    {
        echo "---"
        spdx_header
        echo "# sdk.lock.yaml — GENERATED by \`make lock\`. Do not hand-edit."
        echo "schema: 2"
        echo "sdk_version: \"$(yq -r '.sdk_version' "$MANIFEST")\""
        echo "generated_at: \"$(date -u +%Y-%m-%dT%H:%M:%SZ)\""
        echo "generated_from: ${MANIFEST}"
        echo
        echo "base_image:"
        echo "  pinned:        ${base_pinned}"
        echo "  resolved_from: ${base_ref}"
        echo
        echo "components:"
    } > "$tmp"

    for c in $(yq -r '.components | keys | .[]' "$MANIFEST"); do
        repo=$(yq -r ".components.\"${c}\".repo" "$MANIFEST")
        ref=$(yq  -r ".components.\"${c}\".ref"  "$MANIFEST")
        log "resolving ${c}  ${ref}"
        sha=$(resolve_ref "$repo" "$ref")
        {
            echo "  ${c}:"
            echo "    repo:          ${repo}"
            echo "    commit:        \"${sha}\""
            echo "    resolved_from: ${ref}"
        } >> "$tmp"
    done

    mv "$tmp" "$LOCK"
    log "wrote ${LOCK}"
}

# One bake target "<stage>-pins" per stage, holding the build args of the
# stage's Dockerfile. docker-bake.hcl inherits it.
render_pins() {
    local stage c var out
    for stage in $(yq -r '.stages | keys | .[]' "$MANIFEST"); do
        out="build/${stage}/pins.hcl"
        {
            spdx_header
            echo "# ${out} — GENERATED by \`make lock\` from ${LOCK}. Do not hand-edit."
            if [[ "$stage" == sdk ]]; then
                echo
                printf 'variable "SDK_VERSION" {\n  default = "%s"\n}\n' "$(yq -r '.sdk_version' "$LOCK")"
            fi
            echo
            echo "target \"${stage}-pins\" {"
            echo "  args = {"
            printf '    %-20s = "%s"\n' BASE_IMAGE "$(yq -r '.base_image.pinned' "$LOCK")"
            [[ "$stage" == sdk ]] && printf '    %-20s = %s\n' SDK_VERSION SDK_VERSION
            for c in $(yq -r ".stages.\"${stage}\"[]" "$MANIFEST"); do
                var=$(tr 'a-z-' 'A-Z_' <<< "$c")
                printf '    %-20s = "%s"\n' "${var}_REPO"   "$(yq -r ".components.\"${c}\".repo"   "$LOCK")"
                printf '    %-20s = "%s"\n' "${var}_COMMIT" "$(yq -r ".components.\"${c}\".commit" "$LOCK")"
            done
            echo "  }"
            echo "}"
        } > "$out"
        log "wrote ${out}"
    done
}

case "${1:-}" in
    --render) ;;
    "")       write_lock ;;
    *)        echo "usage: $0 [--render]" >&2; exit 2 ;;
esac
render_pins
